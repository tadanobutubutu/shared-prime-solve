#!/usr/bin/env python3
# =============================================================================
# Shared Prime - Daily AlpacaHack
# カテゴリー: Crypto | トピック: RSA | 難易度: Medium 3.5
# =============================================================================
# 【概要】
# 配布ファイル chall.py は、同じフラグ m を 2 つの RSA 公開鍵で暗号化しています。
#
#   n1 = p * q1      n2 = p * q2      （p が 2 つの鍵で「共有」されている！）
#   c1 = m^e mod n1  c2 = m^e mod n2  （e = 65537）
#
# RSA の安全性は「n を素因数分解するのが難しい」ことに頼っています。
# しかし 2 つの n が同じ素数 p を持っていると、最大公約数 gcd(n1, n2) を
# 計算するだけで p が一瞬で求まってしまいます（素因数分解は不要）。
#
# p が分かれば、あとは教科書どおりの RSA 復号です。
#   q1 = n1 / p  →  φ(n1) = (p-1)(q1-1)  →  d = e^(-1) mod φ(n1)  →  m = c1^d mod n1
#
# （Colab ノートブックと同じく math.gcd → φ → pow(e, -1, phi) → pow(c1, d, n1)
#   → Crypto.Util.number.long_to_bytes の順に計算します）
#
# 【準備】
#   pip install pycryptodome
#   問題ページから配布ファイル (shared-prime.tar.gz) を各自ダウンロードし、
#   展開しておいてください。
#
# 【使い方】
#   python3 solve.py [output.txt へのパス]
#   ※ パスを省略した場合は ./shared-prime/output.txt を読み込みます。
#
# ※ フラグはこのファイルには書かれていません。実行時に計算して表示します。
# =============================================================================

import math  # math.gcd（最大公約数）を使うため（Python 標準ライブラリ）
import re    # output.txt から "n1 = 123..." の形の行を読み取るため
import sys   # コマンドライン引数の取得用

try:
    # long_to_bytes: 大きな整数を元のバイト列（文字列）に戻す関数。
    # chall.py が暗号化前に使っている bytes_to_long のちょうど逆の操作です。
    from Crypto.Util.number import long_to_bytes
except ImportError:
    sys.exit("[!] pycryptodome が見つかりません。`pip install pycryptodome` を実行してください。")

# =============================================================================
# Step 0: output.txt を読み込む
# =============================================================================
# 配布ファイルはリポジトリに含めていないため、ローカルに展開した output.txt を読みます。
# output.txt は chall.py の print(f"{n1 = }") などの出力で、
#   n1 = <10進数の整数>
# という形の行が n1, n2, c1, c2 の 4 行並んでいます。
DEFAULT_PATH = "./shared-prime/output.txt"
path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PATH

try:
    with open(path, encoding="utf-8") as f:
        text = f.read()
except FileNotFoundError:
    sys.exit(f"[!] {path} が見つかりません。配布ファイルを展開し、パスを引数で指定してください。")

# 「名前 = 数字」の組を全部拾って辞書にします。Python の int は桁数無制限なので、
# 600 桁を超える巨大な数でもそのまま扱えます。
values = {name: int(num) for name, num in re.findall(r"(\w+)\s*=\s*(\d+)", text)}
try:
    n1, n2, c1, c2 = values["n1"], values["n2"], values["c1"], values["c2"]
except KeyError as err:
    sys.exit(f"[!] output.txt に {err} が見つかりません。")

# 公開指数 e は output.txt には出力されていませんが、chall.py に e = 65537 と書かれています。
e = 65537

print(f"[*] n1 : {n1.bit_length()} ビット")
print(f"[*] n2 : {n2.bit_length()} ビット")

# =============================================================================
# Step 1: 共有された素数 p を最大公約数で求める
# =============================================================================
# n1 = p * q1, n2 = p * q2 で、p, q1, q2 は互いに異なる素数です。
# 2 つの数に共通して含まれる素因数は p だけなので、
#   gcd(n1, n2) = p
# になります。math.gcd は「ユークリッドの互除法」で計算するため、
# 2047 ビット級の数でも一瞬で終わります（素因数分解とは難しさがまったく違います）。
p = math.gcd(n1, n2)
print(f"[*] p = gcd(n1, n2) : {p.bit_length()} ビット")

# 念のための確認: gcd が 1 なら共通の素数はなく、n1 そのものなら分解できていません。
if not (1 < p < n1):
    sys.exit("[!] gcd から有効な素因数が得られませんでした。")

# =============================================================================
# Step 2: もう一方の素数 q1 を求める
# =============================================================================
# n1 = p * q1 なので、n1 を p で割れば q1 が出ます（割り切れるので // で整数除算）。
q1 = n1 // p
assert p * q1 == n1  # 割り算が正しく割り切れたかの確認
print(f"[*] q1 = n1 // p    : {q1.bit_length()} ビット")

# =============================================================================
# Step 3: オイラーのトーシェント関数 φ(n1) を計算する
# =============================================================================
# n1 が 2 つの異なる素数の積 p * q1 のとき、
#   φ(n1) = (p - 1) * (q1 - 1)
# です。φ(n1) は「1 以上 n1 以下で n1 と互いに素な整数の個数」で、
# 素因数 p, q1 を知っている人にしか計算できません。ここが RSA の秘密の核心です。
phi = (p - 1) * (q1 - 1)

# =============================================================================
# Step 4: 秘密鍵 d を計算する
# =============================================================================
# d は「e * d ≡ 1 (mod φ(n1))」を満たす数、つまり e の φ(n1) を法とする逆元です。
# Python 3.8 以降では pow(e, -1, phi) でモジュラ逆元を直接計算できます。
# （gcd(e, φ(n1)) = 1 でないと逆元は存在しませんが、その場合は ValueError になります）
d = pow(e, -1, phi)

# =============================================================================
# Step 5: c1 を復号して平文 m を得る
# =============================================================================
# RSA の復号は m = c1^d mod n1 です。
# pow(底, 指数, 法) は「繰り返し二乗法」で高速に計算してくれます。
m = pow(c1, d, n1)

# =============================================================================
# Step 6: 整数 m をバイト列に戻して表示する
# =============================================================================
# chall.py は FLAG を bytes_to_long で整数にしてから暗号化しているので、
# long_to_bytes で逆変換すれば元の文字列に戻ります。
flag = long_to_bytes(m)

# （おまけの確認）同じ p を使って 2 本目の鍵 (n2, c2) からも復号し、同じ m になるか確かめます。
q2 = n2 // p
d2 = pow(e, -1, (p - 1) * (q2 - 1))
print(f"[*] (n2, c2) からの復号結果と一致: {pow(c2, d2, n2) == m}")

print("[+] Flag:", flag.decode())
